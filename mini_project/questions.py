def is_hit(doc, gold: list[tuple[str, int, str]], short_name: dict) -> bool:
    """이 청크가 gold 중 하나인가. 공백은 무시하고 본다 — 재귀 분할은 낱말 사이에서 줄이 바뀔 수 있다."""
    m = doc.metadata
    body = "".join(doc.page_content.split())
    return any(short_name.get(m.get("source")) == name and m.get("page") == page and "".join(key.split()) in body
               for name, page, key in gold)


def self_check() -> int:
    """gold 가 실제 청크에 있는지 확인한다 (구조 분할 · 재귀 분할 둘 다). 틀린 gold 로 재면 숫자가 전부 거짓이 된다."""
    import sys
    from collections import Counter

    from langsmith import tracing_context

    import build_index
    from config import SHORT_NAME

    sys.stdout.reconfigure(encoding="utf-8")
    ids = [q[0] for q in QUESTIONS]
    problems = [f"id 중복: {i}" for i, n in Counter(ids).items() if n > 1]
    with tracing_context(enabled=False):
        by_mode = {mode: build_index.build_chunks(mode) for mode in ("structure", "recursive")}
    for qid, kind, _question, gold, must, _bad in QUESTIONS:
        if not must:
            problems.append(f"{qid}: must 가 비어 있음")
        if (kind in NO_RETRIEVAL) != (not gold):
            problems.append(f"{qid}: 유형 {kind} 과 gold 유무가 안 맞음")
        for g in gold:
            for mode, chunks in by_mode.items():
                if not any(is_hit(c, [g], SHORT_NAME) for c in chunks):
                    problems.append(f"{qid}: gold {g} 가 {mode} 청크에 없음")
    print(f"문항 {len(QUESTIONS)}개 —", dict(Counter(q[1] for q in QUESTIONS)))
    for p in problems:
        print("  ❌", p)
    print("✅ gold 가 모두 실제 청크에 있습니다" if not problems else f"❌ {len(problems)}건")
    return 1 if problems else 0


if __name__ == "__main__":
    raise SystemExit(self_check())
